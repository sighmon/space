"""Export the real NR101 point query and hourly timeline for the static web prototype.

Runs the repo's own code (``atlas.cli`` query path and ``atlas.timeline.build_timeline``)
and writes ``web/data/nr101.json`` plus ``web/data/nr101.js`` (the same object assigned to
``window.NR101_DATA``, so ``web/index.html`` also works when opened from ``file://``).

Needs the rasters and SPICE kernels in ``data/raw/`` (see data/MANIFEST.tsv).
No combined score is written. Hourly series are strings of 0/1, one character per hour.
"""

from __future__ import annotations

import argparse
import json
import warnings
from pathlib import Path

from atlas.frame import lonlat_to_xy
from atlas.load import load_bundle
from atlas.sample import cold_shadow_centers, query_point
from atlas.timeline import DEFAULT_KERNELS, DEFAULT_RAW, WINDOW_START, WINDOWS, build_timeline

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = PACKAGE_ROOT / "web" / "data"
NR101_LON = 36.917
NR101_LAT = -85.295
_BANNED = {"score", "safety", "safety_score", "habitability", "habitability_score", "fused_score", "rank", "ranking", "safe"}
# Text fields from the point query that the web card shows; the long *_frame strings are omitted.
_QUERY_KEYS = (
    "slope_deg", "slope_rms_deg", "solar_fraction", "earth_fraction", "summer_max_temperature_k",
    "temperature_resolution_m", "permanent_shadow", "lola_return_count", "interpolated_gap",
    "distance_to_cold_shadow_m", "cuts", "extent", "cold_shadow_note", "solar_label", "earth_label",
    "temperature_label", "slope_citation", "solar_citation", "earth_citation",
    "permanent_shadow_citation", "temperature_citation", "return_count_citation",
)


def build_export(lon: float, lat: float, raw: Path, kernels: Path) -> dict:
    warnings.filterwarnings("ignore", message="You will likely lose important projection information")
    bundle = load_bundle(raw)
    x, y = lonlat_to_xy(lon, lat)
    query = query_point(
        x, y, longitude_deg=lon, latitude_deg=lat, extent=bundle.extent,
        slope=bundle.slope, slope_rms=bundle.slope_rms, returns=bundle.returns,
        solar=bundle.solar, earth=bundle.earth, shadow=bundle.shadow,
        temperature=bundle.temperature, cold_centers=cold_shadow_centers(bundle.shadow, bundle.temperature),
    )
    timeline = build_timeline(lon, lat, raw, kernels)
    windows = {}
    for key, days, label in WINDOWS:
        series = {}
        for name, record in timeline["windows"][key].items():
            series[name] = "".join("1" if v else "0" for v in record["visible"])
        windows[key] = {"label": label, "days": days, "series": series}
    out = {
        "name": "NR101",
        "region": "Nobile Rim 1",
        "provenance": "Generated by atlas/export_web.py from the repository's own query and timeline code.",
        "longitude_deg": lon,
        "latitude_deg": lat,
        "query": {k: query[k] for k in _QUERY_KEYS},
        "timeline": {
            "start": WINDOW_START,
            "step_seconds": 3600,
            "ephemeris": timeline["ephemeris"],
            "surface_elevation_m": timeline["surface_elevation_m"],
            "horizon_note": timeline["horizon_note"],
            "long_term_averages": timeline["long_term_averages"],
            "windows": windows,
            "encoding": "series strings: one character per hour, '1' = any part of the disc is above the terrain horizon",
        },
    }
    _check(out)
    return out


def _check(value) -> None:
    if isinstance(value, dict):
        bad = _BANNED.intersection(value)
        if bad:
            raise RuntimeError(f"combined or verdict key leaked into the export: {sorted(bad)}")
        for child in value.values():
            _check(child)
    elif isinstance(value, list):
        for child in value:
            _check(child)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export NR101 values and timeline for web/.")
    parser.add_argument("--lon", type=float, default=NR101_LON)
    parser.add_argument("--lat", type=float, default=NR101_LAT)
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--kernels", type=Path, default=DEFAULT_KERNELS)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Directory for nr101.json and nr101.js")
    args = parser.parse_args(argv)
    data = build_export(args.lon, args.lat, args.raw, args.kernels)
    args.out.mkdir(parents=True, exist_ok=True)
    text = json.dumps(data, indent=1, sort_keys=True, allow_nan=False)
    (args.out / "nr101.json").write_text(text + "\n")
    (args.out / "nr101.js").write_text("window.NR101_DATA = " + text + ";\n")
    print(f"wrote {args.out / 'nr101.json'} and nr101.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
